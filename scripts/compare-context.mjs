import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, realpathSync, rmdirSync, rmSync, unlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";

const [, , servicePath, revision = "HEAD"] = process.argv;
if (!servicePath || process.argv.length > 4) {
  console.error("Usage: node scripts/compare-context.mjs <seatget-checkout> [service-revision]");
  process.exit(1);
}

function git(cwd, ...args) {
  return execFileSync("git", ["-C", cwd, ...args], { encoding: "utf8" }).trim();
}

function textAt(root, file) {
  const path = join(root, file);
  return existsSync(path) ? readFileSync(path, "utf8") : "";
}

function syncStatus(root, ...args) {
  const script = join(root, ".brain", "scripts", "sync.mjs");
  const result = spawnSync(process.execPath, [script, ...args], { cwd: root, encoding: "utf8" });
  if (result.error) throw result.error;
  if (result.status === null) throw new Error("Brain sync did not finish");
  return result.status;
}

function hasGeneratedRules(root, file) {
  const text = textAt(root, file);
  return text.startsWith("<!-- Generated by SeatGet Brain.") &&
    text.includes("선점 만료와 확정") &&
    text.includes("실행하지 못한 검증");
}

const service = resolve(servicePath);
const serviceRevision = git(service, "rev-parse", "--verify", "--end-of-options", `${revision}^{commit}`);
const gitlink = git(service, "ls-tree", serviceRevision, "--", ".brain");
const brainRevision = gitlink.match(/^160000 commit ([a-f0-9]+)\t\.brain$/)?.[1];
if (!brainRevision) throw new Error("The selected service revision has no pinned .brain submodule");

const origin = git(service, "remote", "get-url", "origin");
const parent = realpathSync(tmpdir());
const temp = realpathSync(mkdtempSync(join(parent, "seatget-context-ab-")));
if (dirname(temp) !== parent || !basename(temp).startsWith("seatget-context-ab-")) {
  throw new Error("Unexpected temporary directory");
}

try {
  const before = join(temp, "a");
  const after = join(temp, "b");
  for (const fixture of [before, after]) {
    git(temp, "clone", "--quiet", "--no-checkout", "--no-hardlinks", "--", service, fixture);
    git(fixture, "checkout", "--quiet", "--detach", serviceRevision);
  }

  for (const file of ["AGENTS.md", "CLAUDE.md"]) {
    if (!hasGeneratedRules(before, file)) throw new Error(`Expected a Brain-generated ${file}`);
    unlinkSync(join(before, file));
  }
  unlinkSync(join(before, ".gitmodules"));
  rmdirSync(join(before, ".brain"));

  git(after, "remote", "set-url", "origin", origin);
  git(after, "submodule", "update", "--init", "--", ".brain");
  const syncCheck = syncStatus(after, "--check");

  const checks = [
    ["mvp", "첫 시연 범위", (root) => textAt(root, "docs/mvp.md").includes("예약을 확정")],
    ["adr", "DB 선택 근거", (root) => textAt(root, "docs/adr/0001-initial-stack.md").includes("MySQL 선택 근거")],
    ["experiment", "부하 비교 조건", (root) => textAt(root, "experiments/README.md").includes("동시 사용자 수")],
    ["codex", "Codex 공통 지침", (root) => hasGeneratedRules(root, "AGENTS.md")],
    ["claude", "Claude Code 공통 지침", (root) => hasGeneratedRules(root, "CLAUDE.md")],
    ["pin", "고정 커밋 및 생성본 일치", (root) => existsSync(join(root, ".brain", ".git")) &&
      git(join(root, ".brain"), "rev-parse", "HEAD") === brainRevision && syncCheck === 0],
  ].map(([id, label, check]) => ({ id, label, a: check(before), b: check(after) }));

  const generated = join(after, "AGENTS.md");
  const original = readFileSync(generated, "utf8");
  writeFileSync(generated, original + "\n<!-- A/B fixture drift -->\n", "utf8");
  const afterEdit = syncStatus(after, "--check");
  const resync = syncStatus(after);
  const afterResync = syncStatus(after, "--check");

  const result = {
    serviceRevision,
    brainRevision,
    checks,
    driftCheck: {
      clean: syncCheck,
      afterEdit,
      resync,
      afterResync,
      restored: readFileSync(generated, "utf8") === original.replaceAll("\r\n", "\n"),
    },
  };
  process.stdout.write(JSON.stringify(result, null, 2) + "\n");
} finally {
  rmSync(temp, { recursive: true, force: true });
}
