import { readFileSync, writeFileSync, lstatSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";

const brainRoot = fileURLToPath(new URL("../", import.meta.url));
const generatedHeader = "<!-- Generated by SeatGet Brain. Edit harness/instructions/common.md in seatget-brain. -->";
const outputs = ["AGENTS.md", "CLAUDE.md"];

function readOutput(filePath) {
  try {
    if (!lstatSync(filePath).isFile()) {
      throw new Error(`지침 출력 경로가 일반 파일이 아닙니다: ${filePath}`);
    }
    return readFileSync(filePath, "utf8").replaceAll("\r\n", "\n");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return null;
  }
}

try {
  const { values } = parseArgs({
    options: { check: { type: "boolean" }, target: { type: "string" } },
  });
  if (!values.target && basename(brainRoot) !== ".brain") {
    throw new Error("독립 Brain 체크아웃에서는 --target으로 서비스 루트를 지정하세요.");
  }
  const target = values.target ? resolve(values.target) : dirname(resolve(brainRoot));
  if (target === resolve(brainRoot)) {
    throw new Error("서비스 저장소 경로를 지정하세요.");
  }

  const source = readFileSync(resolve(brainRoot, "harness/instructions/common.md"), "utf8");
  const instructions = source.replaceAll("\r\n", "\n").trim();
  if (!instructions) throw new Error("공통 작업 지침이 비어 있습니다.");

  const generated = `${generatedHeader}\n# SeatGet 작업 지침\n\n${instructions}\n`;
  const stale = outputs.map((output) => {
    const path = resolve(target, output);
    const current = readOutput(path);
    if (current !== null && !current.startsWith(`${generatedHeader}\n`)) {
      throw new Error(`기존 지침 파일을 유지했습니다: ${path}`);
    }
    return { path, current };
  }).filter(({ current }) => current !== generated);

  if (values.check && stale.length) {
    throw new Error(`동기화가 필요한 파일: ${stale.map(({ path }) => basename(path)).join(", ")}`);
  }
  for (const { path } of stale) {
    writeFileSync(path, generated, "utf8");
    console.log(`생성: ${path}`);
  }
  if (!stale.length) console.log("AI 지침이 공통 원본과 일치합니다.");
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
